def init_db():
    conn = sqlite3.connect('steely_rmi_garage.db')
    c = conn.cursor()
    c.execute('''
        CREATE TABLE IF NOT EXISTS work_orders (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            serial_number TEXT,
            work_order_no TEXT,
            plate_number TEXT,
            vehicle_type TEXT,
            current_reading TEXT,
            reading_unit TEXT,
            job_status TEXT,
            work_category TEXT,
            driver_name TEXT,
            technicians TEXT,
            start_date TEXT,
            end_date TEXT,
            job_description TEXT,
            parts_cost REAL,
            tires_cost REAL,
            total_expenditure REAL
        )
    ''')
    # Spare parts custom breakdown table
    c.execute('''
        CREATE TABLE IF NOT EXISTS spare_parts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            work_order_id INTEGER,
            part_name TEXT,
            part_number TEXT,
            quantity INTEGER,
            unit_price REAL
        )
    ''')
    conn.commit()
    conn.close()

